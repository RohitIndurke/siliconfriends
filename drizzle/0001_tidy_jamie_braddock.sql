CREATE TABLE `job` (
	`id` text PRIMARY KEY NOT NULL,
	`jobTitle` text NOT NULL,
	`employmentType` text NOT NULL,
	`positionType` text NOT NULL,
	`location` text NOT NULL,
	`duration` text NOT NULL,
	`jobFunction` text NOT NULL,
	`companyName` text NOT NULL,
	`companyLogo` text NOT NULL,
	`industry` text NOT NULL,
	`foundedYear` integer,
	`website` text NOT NULL,
	`contactPerson` text NOT NULL,
	`organizationSize` text NOT NULL,
	`baseLocation` text NOT NULL,
	`stipendMonthly` integer,
	`maxIncentivesMonthly` integer,
	`eligibleForFte` integer NOT NULL,
	`ctcFixedLpa` real,
	`ctcVariableLpa` real,
	`requiredSkills` text NOT NULL,
	`goodToHaveSkills` text NOT NULL,
	`description` text NOT NULL,
	`otherDetails` text,
	`eligibilitySummary` text NOT NULL,
	`eligibleCourses` text NOT NULL,
	`selectionProcess` text NOT NULL,
	`status` text NOT NULL,
	`onCampus` integer NOT NULL,
	`opensAt` text NOT NULL,
	`closesAt` text NOT NULL,
	`externalApplyLink` text NOT NULL,
	`createdAt` integer NOT NULL,
	`updatedAt` integer NOT NULL,
	`createdBy` text NOT NULL,
	FOREIGN KEY (`createdBy`) REFERENCES `user`(`id`) ON UPDATE no action ON DELETE no action
);
